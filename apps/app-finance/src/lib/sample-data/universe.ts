const BY_SYMBOL = new Map(UNIVERSE.map((entry) => [entry.symbol, entry]));

export function findInstrument(symbol: string) {
	return BY_SYMBOL.get(symbol.toUpperCase());
}

export function capBucket(capBn: number): "Mega" | "Large" | "Mid" | "Small" {
	if (capBn >= 200) return "Mega";
	if (capBn >= 50) return "Large";
	if (capBn >= 20) return "Mid";
	return "Small";
}
